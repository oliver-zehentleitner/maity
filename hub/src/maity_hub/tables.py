"""The hub's tables: SQLAlchemy Core definitions, the schema `0002` creates.

Field names follow `docs/api.md`. Enumerated values (states, statuses,
kinds, roles) are validated by the API layer, not by CHECK constraints, so
that adding a value within `v1` needs no migration; the constraints here
hold the invariants the server relies on (`docs/architecture.md` §7).

Ids are opaque strings with a readable prefix, generated by the hub
(`maity_hub.ids`). Members are referenced through their membership row;
the API shows the principal's id (`hum-…`, `agt-…`). No table or column is
named after an SQL keyword of any of the three engines (`join`, `key`,
`cursor`, `release` are), so hand-written SQL needs no quoting.

Not in a table, by design for one replica (docs/api.md §8.3): the nonce
window of signed requests and whether a session is `listening`; both move
to the database before a second replica exists. The policy is columns on
`project`, the one-to-one form of architecture §3.6's policy entity; its
history is in the events.
"""

