ID = 40  # length of a hub-generated id
INSTANCE = 5  # an agent instance id, `[2-9a-hjkmnp-z]{4,5}` (§6.17)
HANDLE = 64
TITLE = 200  # characters, docs/api.md §1.7
MARKDOWN = 16384  # characters, docs/api.md §1.7; enforced by the API, see MARKDOWN_TEXT
HEX_SHA256 = 64


def _id(name: str = "id", **kwargs: object) -> Column[str]:
    return Column(name, String(ID), **kwargs)  # type: ignore[arg-type]


def _ref(name: str, target: str, **kwargs: object) -> Column[str]:
    return Column(name, String(ID), ForeignKey(target), **kwargs)  # type: ignore[arg-type]


def _membership_ref(name: str, **kwargs: object) -> Column[int]:
    return Column(name, Integer, ForeignKey("membership.id"), **kwargs)  # type: ignore[arg-type]


def _audit() -> list[Column[str]]:
    """Which credential made the last change, and how it authenticated.

    `changed_via` is `signed`, `bearer` or `cookie`; for a cookie session
    `changed_by_credential` is null and the event's actor names the human.
    """
    return [
        Column("changed_by_credential", String(ID)),
        Column("changed_via", String(16)),
    ]


