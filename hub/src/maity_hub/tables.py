# --- events ----------------------------------------------------------------------------

# Append-only. The one UPDATE allowed is the redaction tombstone, which
# replaces `payload`, sets `redacted` and is itself recorded as an event.
event = Table(
    "event",
    metadata,
    Column("seq", BIG_ID, primary_key=True, autoincrement=True),
    _ref("project_id", "project.id", nullable=False),
    Column("kind", String(32), nullable=False),
    Column("at", UtcDateTime, nullable=False),
    _membership_ref("actor_membership"),
    Column("actor_session_id", String(ID)),
    Column("actor_credential_id", String(ID)),
    Column("actor_via", String(16)),  # signed, bearer, cookie; null for the hub
    Column("actor_harness", String(TITLE)),
    Column("actor_model", String(TITLE)),
    Column("subject_type", String(32)),
    Column("subject_id", String(ID)),
    Column("audience", JSON, nullable=False),
    # The agent's member id for a chat message (docs/api.md §9), else null.
    Column("conversation_id", String(ID)),
    Column("payload", JSON, nullable=False),
    Column("redacted", Boolean, nullable=False),
    Index("ix_event_project_seq", "project_id", "seq"),
    Index("ix_event_conversation", "project_id", "conversation_id", "seq"),
)

# First delivery of a chat message to its recipient. Kept beside the event,
# because the event row itself is never updated.
message_delivery = Table(
    "message_delivery",
    metadata,
    Column("seq", BIG_ID, ForeignKey("event.seq"), primary_key=True),
    Column("delivered_at", UtcDateTime, nullable=False),
)

# How far a human has read a conversation: `unread` counts the agent's
# messages after `last_seq`.
conversation_read = Table(
    "conversation_read",
    metadata,
    _membership_ref("reader", nullable=False),
    Column("conversation_id", String(ID), nullable=False),
    Column("last_seq", BIG_ID, nullable=False),
    PrimaryKeyConstraint("reader", "conversation_id"),
)

