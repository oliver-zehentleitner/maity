"""The hub's tables: SQLAlchemy Core definitions, the schema `0002` creates.

Field names follow `docs/api.md`. Enumerated values (states, statuses,
kinds, roles) are validated by the API layer, not by CHECK constraints, so
that adding a value within `v1` needs no migration; the constraints here
hold the invariants the server relies on (`docs/architecture.md` §7).

Ids are opaque strings with a readable prefix, generated by the hub
(`maity_hub.ids`). Members are referenced through their membership row;
the API shows the principal's id (`hum-…`, `agt-…`). No table or column is
named after an SQL keyword of any of the three engines (`join`, `key`,
`cursor`, `release` are), so hand-written SQL needs no quoting.
"""

from __future__ import annotations

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    ForeignKey,
    Index,
    Integer,
    PrimaryKeyConstraint,
    String,
    Table,
    UniqueConstraint,
)

from maity_hub.db import metadata
from maity_hub.types import BIG_ID, MARKDOWN_TEXT, UtcDateTime

ID = 40  # length of a hub-generated id
HANDLE = 64
TITLE = 200  # characters, docs/api.md §1.7
MARKDOWN = 16384  # characters, docs/api.md §1.7; enforced by the API, see MARKDOWN_TEXT
HEX_SHA256 = 64


def _id(name: str = "id", **kwargs: object) -> Column[str]:
    return Column(name, String(ID), **kwargs)  # type: ignore[arg-type]


def _ref(name: str, target: str, **kwargs: object) -> Column[str]:
    return Column(name, String(ID), ForeignKey(target), **kwargs)  # type: ignore[arg-type]


def _membership_ref(name: str, **kwargs: object) -> Column[int]:
    return Column(name, Integer, ForeignKey("membership.id"), **kwargs)  # type: ignore[arg-type]


def _audit() -> list[Column[str]]:
    """Which credential made the last change, and how it authenticated.

    `changed_via` is `signed`, `bearer` or `cookie`; for a cookie session
    `changed_by_credential` is null and the event's actor names the human.
    """
    return [
        Column("changed_by_credential", String(ID)),
        Column("changed_via", String(16)),
    ]


# --- principals --------------------------------------------------------------

human = Table(
    "human",
    metadata,
    _id(primary_key=True),
    Column("handle", String(HANDLE), nullable=False, unique=True),
    Column("display_name", String(TITLE), nullable=False),
    Column("password_hash", String(255), nullable=False),  # scrypt, with parameters and salt
    Column("created_at", UtcDateTime, nullable=False),
    Column("last_seen_at", UtcDateTime),
)

agent_profile = Table(
    "agent_profile",
    metadata,
    _id(primary_key=True),
    _ref("owner_id", "human.id", nullable=False),
    Column("handle", String(HANDLE), nullable=False),
    Column("display_name", String(TITLE), nullable=False),
    Column("git_name", String(TITLE)),
    Column("git_email", String(TITLE)),
    Column("created_at", UtcDateTime, nullable=False),
    UniqueConstraint("owner_id", "handle"),
)

# A human's dashboard login. The cookie carries a random id; the table holds
# its SHA-256, so a copy of the database opens no session.
human_session = Table(
    "human_session",
    metadata,
    Column("id_hash", String(HEX_SHA256), primary_key=True),
    _ref("human_id", "human.id", nullable=False, index=True),
    Column("csrf_token", String(HEX_SHA256), nullable=False),
    Column("created_at", UtcDateTime, nullable=False),
    Column("last_seen_at", UtcDateTime, nullable=False),
    Column("expires_at", UtcDateTime, nullable=False),
    Column("ended_at", UtcDateTime),
    Column("source", String(64)),
)

# --- projects and memberships -------------------------------------------------

project = Table(
    "project",
    metadata,
    _id(primary_key=True),
    Column("slug", String(HANDLE), nullable=False, unique=True),
    Column("name", String(TITLE), nullable=False),
    Column("state", String(16), nullable=False),
    Column("state_note", MARKDOWN_TEXT),
    Column("state_changed_at", UtcDateTime, nullable=False),
    Column("repository_url", String(255)),
    Column("repository_default_branch", String(255)),
    Column("keep_the_why", Boolean, nullable=False),
    # The policy (docs/api.md §6.1); its history is in the events.
    Column("policy_preset", String(32), nullable=False),
    Column("claim_policy", String(32), nullable=False),
    Column("done_authority", String(32), nullable=False),
    Column("contract_arbiter", String(ID + 8), nullable=False),  # member id or role:admin
    Column("tag_authority", String(32), nullable=False),
    Column("steward_writes", String(32), nullable=False),
    Column("lease_seconds", Integer, nullable=False),
    Column("absence_until", UtcDateTime),
    Column("absence_scope", MARKDOWN_TEXT),
    Column("settings", JSON, nullable=False),
    Column("rules_markdown", MARKDOWN_TEXT),
    Column("rules_version", Integer, nullable=False),
    Column("created_at", UtcDateTime, nullable=False),
)

membership = Table(
    "membership",
    metadata,
    Column("id", Integer, primary_key=True, autoincrement=True),
    _ref("project_id", "project.id", nullable=False),
    _ref("human_id", "human.id"),
    _ref("agent_id", "agent_profile.id"),
    Column("role", String(16), nullable=False),
    _membership_ref("reports_to"),
    Column("areas", JSON, nullable=False),
    Column("capabilities", JSON, nullable=False),
    Column("paused_reason", MARKDOWN_TEXT),
    Column("paused_since", UtcDateTime),
    Column("paused_by", String(ID)),
    Column("joined_at", UtcDateTime, nullable=False),
    Column("last_seen_at", UtcDateTime),
    Column("removed_at", UtcDateTime),
    CheckConstraint(
        "(human_id IS NULL AND agent_id IS NOT NULL)"
        " OR (human_id IS NOT NULL AND agent_id IS NULL)",
        name="one_principal",
    ),
    UniqueConstraint("project_id", "human_id"),
    UniqueConstraint("project_id", "agent_id"),
)

# --- joining and credentials ----------------------------------------------------

join_link = Table(
    "join_link",
    metadata,
    _id(primary_key=True),
    _ref("project_id", "project.id", nullable=False, index=True),
    Column("token_hash", String(HEX_SHA256), nullable=False, unique=True),
    Column("code_hash", String(HEX_SHA256), nullable=False),
    # Either an existing profile, or the handle and name of one the exchange creates.
    _ref("agent_id", "agent_profile.id"),
    Column("new_agent_handle", String(HANDLE)),
    Column("new_agent_display_name", String(TITLE)),
    Column("role", String(16), nullable=False),
    _membership_ref("reports_to"),
    Column("areas", JSON, nullable=False),
    Column("capabilities", JSON, nullable=False),
    _ref("created_by", "human.id", nullable=False),
    Column("created_at", UtcDateTime, nullable=False),
    Column("expires_at", UtcDateTime, nullable=False),
    Column("used_at", UtcDateTime),
    Column("failed_attempts", Integer, nullable=False),
    Column("burned_at", UtcDateTime),
    Column("revoked_at", UtcDateTime),
    CheckConstraint("agent_id IS NOT NULL OR new_agent_handle IS NOT NULL", name="names_an_agent"),
)

credential = Table(
    "credential",
    metadata,
    _id(primary_key=True),
    _membership_ref("membership_id", nullable=False, index=True),
    # sha256 over the secret's text, hex; the HMAC key and the bearer verifier.
    Column("verifier", String(HEX_SHA256), nullable=False),
    _ref("join_id", "join_link.id"),
    Column("client", String(TITLE)),
    Column("created_at", UtcDateTime, nullable=False),
    Column("resumed_at", UtcDateTime),
    Column("last_used_at", UtcDateTime),
    Column("revoked_at", UtcDateTime),
    Column("revoked_by", String(ID)),
    Column("revoked_reason", String(64)),
)

agent_session = Table(
    "agent_session",
    metadata,
    _id(primary_key=True),
    _ref("credential_id", "credential.id", nullable=False),
    _membership_ref("membership_id", nullable=False, index=True),
    Column("harness", String(TITLE)),
    Column("harness_version", String(64)),
    Column("model", String(TITLE)),
    Column("client", String(TITLE)),
    Column("user_agent", String(255)),
    Column("started_at", UtcDateTime, nullable=False),
    Column("last_seen_at", UtcDateTime, nullable=False),
    Column("ended_at", UtcDateTime),
    Column("acknowledged_seq", BIG_ID, nullable=False),  # the cursor: highest `after` seen
    # True while the session is the credential's live one, NULL afterwards:
    # the unique constraint allows one live session per credential and any
    # number of ended ones, on every engine (no partial index needed).
    Column("live", Boolean),
    UniqueConstraint("credential_id", "live", name="uq_agent_session_one_live"),
)

idempotency_key = Table(
    "idempotency_key",
    metadata,
    # A credential id, or the human id for a cookie session that sent a key.
    Column("caller", String(ID), nullable=False),
    Column("idem_key", String(128), nullable=False),
    Column("body_hash", String(HEX_SHA256), nullable=False),
    Column("status_code", Integer, nullable=False),
    Column("resource_type", String(32)),
    Column("resource_id", String(ID)),
    Column("created_at", UtcDateTime, nullable=False, index=True),
    PrimaryKeyConstraint("caller", "idem_key"),
)

# --- cards ------------------------------------------------------------------------

card = Table(
    "card",
    metadata,
    _id(primary_key=True),
    _ref("project_id", "project.id", nullable=False),
    Column("kind", String(32), nullable=False),
    Column("title", String(TITLE), nullable=False),
    Column("body", MARKDOWN_TEXT),
    Column("label", String(16)),
    Column("status", String(16), nullable=False),
    Column("status_before_block", String(16)),
    Column("area", String(255)),
    _membership_ref("created_by", nullable=False),
    _membership_ref("assigned_to"),
    # The claim. One holder per card by construction; the claim is one
    # conditional UPDATE ... WHERE claim_holder IS NULL (docs/architecture.md §7).
    _membership_ref("claim_holder"),
    Column("claim_session_id", String(ID)),
    Column("claim_since", UtcDateTime),
    Column("lease_until", UtcDateTime),
    Column("checkpoint", JSON),
    # No foreign key: request.task_id points back here.
    Column("blocked_by_request", String(ID)),
    Column("ktw_ref", String(255)),
    Column("report", JSON),
    Column("contract", JSON),
    # Releases: the version is unique per project; `release_in_flight` is
    # True on the one release card that is neither done nor cancelled and
    # NULL on every other card, so the unique constraint allows one per project.
    Column("release_version", String(64)),
    Column("release_data", JSON),
    Column("release_in_flight", Boolean),
    *_audit(),
    Column("created_at", UtcDateTime, nullable=False),
    Column("updated_at", UtcDateTime, nullable=False),
    Column("closed_at", UtcDateTime),
    UniqueConstraint("project_id", "release_version"),
    UniqueConstraint("project_id", "release_in_flight", name="uq_card_one_release_in_flight"),
    Index("ix_card_project_updated", "project_id", "updated_at"),
    Index("ix_card_claim_holder", "claim_holder"),
)

card_edge = Table(
    "card_edge",
    metadata,
    _ref("from_card", "card.id", nullable=False),
    _ref("to_card", "card.id", nullable=False, index=True),
    Column("kind", String(16), nullable=False),  # depends_on, ships_with
    PrimaryKeyConstraint("from_card", "to_card", "kind"),
    CheckConstraint("from_card <> to_card", name="no_self_edge"),
)

