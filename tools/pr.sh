#!/usr/bin/env bash
# Open a pull request, or edit its title and body, over GitHub's REST API: for sessions whose
# GitHub tool or GraphQL is refused (Claude Code's cloud sessions), where `gh pr create` and
# `gh pr edit` cannot work.
#
#   tools/pr.sh open --title T --body-file F [--base B] [--draft] [<branch>]
#   tools/pr.sh edit <number> [--title T] [--body-file F] [--branch B]
#
# open: POST repos/{owner}/{repo}/pulls with head <branch> (default: the checked-out branch) and
# base B (default main). It refuses unless origin has the branch at the same commit as the local
# branch, so a pull request is never opened for work that is not pushed.
# edit: PATCH repos/{owner}/{repo}/pulls/<number> with the fields given. It refuses an edit that
# names no field, and a pull request whose head is not the checked-out branch (or B) in origin's
# repository: every agent pushes as the same GitHub account, so the head ref, not the author, is
# what keeps an agent to its own pull request. A guard against mistakes, not an access control.
#
# The body always comes from a file, sent as its UTF-8 text with line endings made LF, the
# same text the check reads: no shell quoting of Markdown. Both refuse a body with one of these
# lines (pull requests here carry no attribution), and only these: a line that starts, in any
# case, after nothing but spaces, emoji, symbols, `>` and Markdown emphasis or link markup,
# with "Generated with", "Generated by", "Co-Authored-By:" or "Claude-Session:"
# (`_Generated by [Claude Code](...)_`, `- Co-Authored-By: ...`, `> Claude-Session: ...`), or
# with Co-Authored-By or Claude-Session as the text of an inline or a full or collapsed
# reference link (`[Co-Authored-By](`, `[Co-Authored-By][`), whatever follows. The same words
# mid-line, as in a sentence describing this rule, are text. Not detected: a shortcut reference
# link (`[Co-Authored-By]: ...` with a definition elsewhere) and any other Markdown that renders
# such a label. This is a safety net against the lines tools write by accident, not a Markdown
# sanitiser (the lead's scope for #1507). Nothing else is sent, and nothing is added.
#
# Owner, repository and host are origin's, read from `remote.origin.url`, never gh's own choice
# (GH_HOST, GH_REPO, `gh repo set-default`, another logged-in host). Only these forms are read,
# with exactly owner/repo after the host (".git" and one trailing "/" allowed): scp-style
# `[user@]host:owner/repo`, `ssh://`, `https://` or `http://` `[user@]host[:port]/owner/repo`, and
# a loopback proxy (`http://127.0.0.1:<port>/git/owner/repo`, which stands for github.com). Any
# other URL, a query, a fragment, more or fewer path segments, or "." and ".." as a name, is
# refused before any call to GitHub.
# On success it prints what GitHub answered: number, URL, head commit and title.
#
# Exit 0 done, 1 refused (the reason on stderr), 2 could not run (a git or gh call failed, or
# GitHub's answer was not what was asked). A run that did not reach GitHub never ends in 0.
set -uo pipefail

die() {
  echo "pr: $*" >&2
  exit 2
}

refuse() {
  echo "pr: $*" >&2
  exit 1
}

usage() {
  sed -n '7,8p' "$0" | sed 's/^# //' >&2
  exit 2
}

git() {
  command git -c core.quotePath=false "$@"
}

# JSON is built and read by Python, not by the shell: no quoting, no gh field magic (`-F`
# converts "true" and numbers), the same bytes in as out. -I: no file next to the caller runs.
py() {
  python3 -I -c "$@"
}

[ $# -ge 1 ] || usage
action=$1
shift
case $action in
  open | edit) ;;
  -h | --help) usage ;;
  *) die "unknown action '$action' (open or edit)" ;;
esac

title="" title_set=0 body_file="" base=main draft=0 branch="" number=""
while [ $# -gt 0 ]; do
  case $1 in
    --title)
      [ $# -ge 2 ] || die "--title needs a value"
      title=$2 title_set=1
      shift 2
      ;;
    --body-file)
      [ $# -ge 2 ] || die "--body-file needs a file"
      body_file=$2
      shift 2
      ;;
    --base)
      [ "$action" = open ] || die "--base is for open"
      [ $# -ge 2 ] || die "--base needs a branch"
      base=$2
      shift 2
      ;;
    --draft)
      [ "$action" = open ] || die "--draft is for open"
      draft=1
      shift
      ;;
    --branch)
      [ "$action" = edit ] || die "--branch is for edit (open takes the branch as its argument)"
      [ $# -ge 2 ] || die "--branch needs a branch"
      branch=$2
      shift 2
      ;;
    -*) die "unknown option $1" ;;
    *)
      if [ "$action" = edit ] && [ -z "$number" ]; then
        number=$1
      elif [ "$action" = open ] && [ -z "$branch" ]; then
        branch=$1
      else
        die "unexpected argument $1"
      fi
      shift
      ;;
  esac
done

# --- origin's repository and host ------------------------------------------------------------
# The URL as configured: `git remote get-url` applies url.<base>.insteadOf, which can name a
# mirror whose path is not the repository's on GitHub.
origin=$(git config --get remote.origin.url) || die "no remote origin"
unreadable() {
  die "cannot read an owner and a repository from origin's URL $origin (supported: [user@]host:owner/repo, ssh://, https:// or http://[user@]host[:port]/owner/repo)"
}
# No query, fragment, whitespace or backslash anywhere: git and this parser could read them apart.
[[ $origin != *[?#\\[:space:]]* && -n $origin ]] || unreadable
if [[ $origin =~ ^(https?|ssh)://([^/@]*@)?([^/@]+)/(.*)$ ]]; then
  authority=${BASH_REMATCH[3]}
  path=${BASH_REMATCH[4]}
elif [[ $origin =~ ^([^/@:]+@)?([^/@:]+):([^/].*)$ ]]; then # scp-style; no scheme, no port
  authority=${BASH_REMATCH[2]}
  path=${BASH_REMATCH[3]}
else
  unreadable
fi
case $authority in
  \[*\]) repo_host=$authority ;;
  \[*\]:*) repo_host=${authority%%]*}] ;;
  *:*:*) unreadable ;;
  *) repo_host=${authority%%:*} ;;
esac
repo_host=${repo_host,,}
path=${path%/}
path=${path%.git}
# A host on the loopback is a proxy in front of github.com (cloud sessions fetch through one),
# which serves the repository under /git/.
if [[ $repo_host == localhost || $repo_host == "[::1]" || $repo_host =~ ^127(\.[0-9]{1,3}){3}$ ]]; then
  repo_host=github.com
  path=${path#git/}
fi
[[ $repo_host =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$ ]] \
  || die "cannot read a host from origin's URL $origin"
[[ $path =~ ^([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)$ ]] || unreadable
repo_owner=${BASH_REMATCH[1]}
repo_name=${BASH_REMATCH[2]}
for name in "$repo_owner" "$repo_name"; do
  [[ $name != . && $name != .. ]] || unreadable
done
repo="$repo_owner/$repo_name"

# --- the body ---------------------------------------------------------------------------------
if [ -n "$body_file" ]; then
  [ -f "$body_file" ] && [ -r "$body_file" ] || die "cannot read the body file $body_file"
  # One reading for the check and the request: the body as UTF-8 with its line endings made LF
  # (`\r\n` and a lone `\r`), written once to a file of our own; the check reads that file and
  # the request sends it, so a line Markdown would start at a carriage return is a line here too
  # (review of #1507, delta 5).
  normalised=$(mktemp) || die "cannot make a temporary file for the body"
  trap 'rm -f "$normalised"' EXIT
  py '
import sys
with open(sys.argv[1], "rb") as f:
    text = f.read().decode("utf-8")
text = text.replace("\r\n", "\n").replace("\r", "\n")
with open(sys.argv[2], "w", encoding="utf-8", newline="") as f:
    f.write(text)
' "$body_file" "$normalised" || die "cannot read the body file $body_file as UTF-8"
  body_file=$normalised
  # The fixed list, at a line's start after anything but letters and digits (spaces, emoji,
  # symbols, `>`, emphasis, link markup), in any case; emphasis may come before the colon
  # (`**Co-Authored-By**:`). A Co-Authored-By or Claude-Session label as the text of an
  # inline or a full or collapsed reference link, `[Co-Authored-By](` or `[Co-Authored-By][`,
  # is refused whatever follows: destination, title, line breaks and the colon after the link
  # are CommonMark's to read, not this check's (review of #1507, delta 4). A shortcut reference
  # link is not detected (the header says what else is not). In the C locale every byte of an
  # emoji is such a character.
  attribution='^[^[:alnum:]]*(generated[[:space:]]+(with|by)([^[:alnum:]]|$)|(co-authored-by|claude-session)[*_]*(:|\][[(]))'
  found=$(LC_ALL=C grep -Ein -m 1 -- "$attribution" "$body_file")
  status=$?
  case $status in
    0) refuse "the body has an attribution line (line ${found%%:*}: Generated with, Generated by, Co-Authored-By: or Claude-Session: at its start, or one of the last two as a link); pull requests here carry none" ;;
    1) ;;
    *) die "cannot check the body for attribution lines (grep exit $status): nothing sent" ;;
  esac
fi

# The request's JSON from the arguments: py reads the body file itself, as bytes decoded UTF-8.
request_json() {
  py '
import json, sys
fields = {}
args = sys.argv[1:]
for key, value in zip(args[::2], args[1::2]):
    if key == "body":
        with open(value, encoding="utf-8", newline="") as f:  # already LF only
            fields["body"] = f.read()
    elif key == "draft":
        fields["draft"] = value == "1"
    else:
        fields[key] = value
print(json.dumps(fields))
' "$@"
}

# One field of GitHub's JSON answer on stdin, by a dotted path ("head.ref"); empty when absent.
field() {
  py '
import json, sys
value = json.load(sys.stdin)
for part in sys.argv[1].split("."):
    value = value.get(part) if isinstance(value, dict) else None
print("" if value is None else value)
' "$1"
}

# What GitHub answered, printed in one piece: it fails as a whole, never with a field left empty.
report() {
  local out
  out=$(py '
import json, sys
a = json.load(sys.stdin)
print("#%s %s\n  head %s\n  title %s" % (a["number"], a["html_url"], a["head"]["sha"], a["title"]))
' <<<"$1") || die "the change was sent, but GitHub's answer cannot be read: check the pull request"
  printf '%s\n' "$out"
}

if [ "$action" = open ]; then
  [ "$title_set" = 1 ] && [ -n "$title" ] || refuse "open needs --title"
  [ -n "$body_file" ] || refuse "open needs --body-file"
  if [ -z "$branch" ]; then
    branch=$(git symbolic-ref --quiet --short HEAD) || refuse "no branch checked out; name it"
  fi
  [ "$branch" != "$base" ] || refuse "the branch is the base ($base)"
  local_head=$(git rev-parse --verify --quiet "refs/heads/$branch^{commit}") \
    || refuse "no local branch $branch"
  remote=$(git ls-remote origin "refs/heads/$branch") || die "cannot read origin's branches (git ls-remote)"
  remote_head=${remote%%[[:space:]]*}
  [ -n "$remote_head" ] || refuse "origin has no branch $branch: push it first"
  [ "$remote_head" = "$local_head" ] \
    || refuse "origin's $branch is at ${remote_head:0:12}, the local one at ${local_head:0:12}: push first"
  args=(title "$title" head "$branch" base "$base" body "$body_file")
  [ "$draft" = 1 ] && args+=(draft 1)
  payload=$(request_json "${args[@]}") || die "cannot build the request"
  answer=$(gh api --hostname "$repo_host" -X POST "repos/$repo/pulls" --input - <<<"$payload") \
    || die "opening the pull request on $repo ($repo_host) failed (gh api)"
  [ "$(field head.sha <<<"$answer")" = "$local_head" ] \
    || die "GitHub answered with another head than $local_head: $(field html_url <<<"$answer")"
  report "$answer"
  exit 0
fi

# --- edit -------------------------------------------------------------------------------------
[[ $number =~ ^[1-9][0-9]*$ ]] || refuse "edit needs a pull request number"
[ "$title_set" = 1 ] || [ -n "$body_file" ] || refuse "edit names no field: give --title or --body-file"
[ "$title_set" = 0 ] || [ -n "$title" ] || refuse "the title cannot be empty"
if [ -z "$branch" ]; then
  branch=$(git symbolic-ref --quiet --short HEAD) || refuse "no branch checked out; give --branch"
fi
current=$(gh api --hostname "$repo_host" "repos/$repo/pulls/$number") \
  || die "reading pull request #$number of $repo ($repo_host) failed (gh api)"
head_ref=$(field head.ref <<<"$current") || die "cannot read #$number's head from GitHub's answer"
head_repo=$(field head.repo.full_name <<<"$current") || die "cannot read #$number's head from GitHub's answer"
[ "$head_repo" = "$repo" ] || refuse "#$number's head is in ${head_repo:-a deleted repository}, not $repo"
[ "$head_ref" = "$branch" ] || refuse "#$number's head is $head_ref, not $branch: edit only your own pull request"
args=()
[ "$title_set" = 1 ] && args+=(title "$title")
[ -n "$body_file" ] && args+=(body "$body_file")
payload=$(request_json "${args[@]}") || die "cannot build the request"
answer=$(gh api --hostname "$repo_host" -X PATCH "repos/$repo/pulls/$number" --input - <<<"$payload") \
  || die "editing pull request #$number of $repo ($repo_host) failed (gh api)"
[ "$(field number <<<"$answer")" = "$number" ] || die "GitHub answered for another pull request"
report "$answer"
