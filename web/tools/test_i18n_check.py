def table(*rows):
    head = "| English | de | fr | es | it | pt | nl | ja | ko | zh-Hans |\n|---|---|---|---|---|---|---|---|---|---|\n"
    return head + "".join("| %s | a | b | c | d | %s | f | g | h | i |\n" % row for row in rows)


