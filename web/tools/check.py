#!/usr/bin/env python3
"""Checks for the Maity dashboard, on the Python standard library alone.

    python3 tools/check.py           check everything, exit 1 on any finding
    python3 tools/check.py --write   regenerate fixtures/fixtures.js and
                                     js/i18n/*.js first, lower the strings baseline

What is checked:

- fixtures: every project in me.json has its fixture files; every
  fixtures/**/*.json parses; fixtures/fixtures.js is the
  current bundle of them (the page loads that file, since file:// cannot
  fetch JSON; see context/fixtures.md).
- html: index.html is well-formed (balanced tags, void elements, quoted
  structure), has doctype, lang, charset, viewport and title, unique ids,
  every <label for> points at an id, every local src/href exists, every
  js/*.js file is loaded, no inline scripts, styles or event handlers.
- js: "use strict"; balanced brackets outside strings, comments and
  regular expressions; none of the HTML-parsing or code-evaluating calls
  (context/rendering.md); no native append/prepend outside js/dom.js;
  no fragment route (#/), location.hash or History API outside
  js/route.js (context/routing.md);
  no var, console or debugger; plus
  `node --check` per file when a node binary happens to be on the PATH
  (it is not required, and its absence is reported, not hidden).
- i18n: every i18n/<lang>.json parses, its keys are dotted lowercase
  names, each text a string or plural forms with `other`, with no
  placeholder English lacks; js/i18n/<lang>.js is the current bundle of it;
  M.t takes its key as a string literal the English catalog holds, and
  every English key is used. Text in the views is ratcheted: each js file
  may hold no more prose string literals than tools/strings-baseline.json
  allows (`--write` lowers the baseline, never raises it), so new text goes
  through the catalog (context/rendering.md).
- hub/src/maity_hub/landing_assets/landing.js, the public landing page's
  one script (§16.7), served by the hub: at
  most 10 KiB, the rules above, and no request (fetch, XMLHttpRequest,
  WebSocket, EventSource, sendBeacon, import(), setting a src or href).
- css: balanced braces; every var(--x) is defined.
- all text files: no tabs, no trailing whitespace, final newline.
"""

import html.parser
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES = os.path.join(ROOT, "fixtures")
BUNDLE = os.path.join(FIXTURES, "fixtures.js")
BUNDLE_HEADER = (
    "// Generated by tools/check.py --write from fixtures/**/*.json. Do not edit.\n"
    "// The page loads this file because file:// cannot fetch() the JSON.\n"
)

findings = []


def finding(path, line, message):
    findings.append("%s:%s: %s" % (os.path.relpath(path, ROOT), line, message))


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


# ---- fixtures ---------------------------------------------------------------

def fixture_files():
    """Relative paths of all fixtures, "me.json", "maity/requests.json", ..."""
    found = []
    for dirpath, dirnames, filenames in os.walk(FIXTURES):
        dirnames.sort()
        for name in filenames:
            if name.endswith(".json"):
                rel = os.path.relpath(os.path.join(dirpath, name), FIXTURES)
                found.append(rel.replace(os.sep, "/"))
    return sorted(found)


def build_bundle():
    data = {}
    for name in fixture_files():
        path = os.path.join(FIXTURES, name)
        try:
            data[name] = json.loads(read(path))
        except json.JSONDecodeError as e:
            finding(path, e.lineno, "invalid JSON: %s" % e.msg)
    body = json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True)
    return BUNDLE_HEADER + '"use strict";\n\nwindow.MAITY_FIXTURES = ' + body + ";\n"


# Every project in me.json answers every endpoint the views call.
PROJECT_FIXTURES = ("project.json", "members.json", "requests.json", "tasks.json",
                    "credentials.json", "conversations.json", "joins.json")
TOP_FIXTURES = ("me.json", "auth-session.json", "agents.json", "runners.json", "runner-enrollments.json", "admin-users.json")


def check_fixture_set():
    present = set(fixture_files())
    for name in TOP_FIXTURES:
        if name not in present:
            finding(os.path.join(FIXTURES, name), 1, "missing fixture")
    if "me.json" not in present:
        return
    try:
        me = json.loads(read(os.path.join(FIXTURES, "me.json")))
    except json.JSONDecodeError:
        return
    for project in me.get("projects", []):
        for name in PROJECT_FIXTURES:
            rel = project["slug"] + "/" + name
            if rel not in present:
                finding(os.path.join(FIXTURES, rel), 1, "missing fixture for project %s" % project["slug"])


def check_fixtures(write):
    check_fixture_set()
    bundle = build_bundle()
    if write:
        with open(BUNDLE, "w", encoding="utf-8") as f:
            f.write(bundle)
    elif not os.path.exists(BUNDLE) or read(BUNDLE) != bundle:
        finding(BUNDLE, 1, "stale bundle: run `make fixtures`")


# ---- html -------------------------------------------------------------------

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "source", "track", "wbr"}
# Elements whose end tag may be omitted; not used here, so not tolerated.
OPTIONAL_END = set()


class HtmlChecker(html.parser.HTMLParser):
    def __init__(self, path):
        super().__init__(convert_charrefs=True)
        self.path = path
        self.stack = []
        self.ids = {}
        self.label_fors = []
        self.local_refs = []
        self.scripts = []
        self.doctype = False
        self.lang = False
        self.charset = False
        self.viewport = False
        self.title_text = None
        self._in_title = False
        self._in_script = False

    def err(self, message):
        finding(self.path, self.getpos()[0], message)

    def handle_decl(self, decl):
        if decl.lower() == "doctype html":
            self.doctype = True

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        names = [n for n, _ in attrs]
        if len(names) != len(set(names)):
            self.err("duplicate attribute on <%s>" % tag)
        for name in names:
            if name.startswith("on"):
                self.err("inline event handler %s on <%s>" % (name, tag))
        if "style" in a:
            self.err("inline style on <%s>" % tag)
        if "id" in a:
            if a["id"] in self.ids:
                self.err("duplicate id %r" % a["id"])
            self.ids[a["id"]] = self.getpos()[0]
        if tag == "html" and a.get("lang"):
            self.lang = True
        if tag == "meta" and a.get("charset", "").lower() == "utf-8":
            self.charset = True
        if tag == "meta" and a.get("name") == "viewport":
            self.viewport = True
        if tag == "label" and "for" in a:
            self.label_fors.append((a["for"], self.getpos()[0]))
        if tag == "img" and "alt" not in a:
            self.err("<img> without alt")
        for attr in ("src", "href"):
            ref = a.get(attr)
            if ref and not re.match(r"^(#|[a-z]+:|//|\?)", ref):
                self.local_refs.append((ref, self.getpos()[0]))
        if tag == "script":
            if "src" not in a:
                self._in_script = True
            else:
                self.scripts.append(a["src"])
        if tag == "title":
            self._in_title = True
            self.title_text = ""
        if tag not in VOID:
            self.stack.append((tag, self.getpos()[0]))

    def handle_startendtag(self, tag, attrs):
        if tag not in VOID:
            self.err("self-closing non-void element <%s/>" % tag)
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.stack.pop()

    def handle_endtag(self, tag):
        if tag in VOID:
            self.err("end tag for void element </%s>" % tag)
            return
        if not self.stack:
            self.err("unexpected </%s>" % tag)
            return
        open_tag, line = self.stack.pop()
        if open_tag != tag:
            self.err("</%s> closes <%s> from line %d" % (tag, open_tag, line))
        if tag == "title":
            self._in_title = False
        if tag == "script":
            self._in_script = False

    def handle_data(self, data):
        if self._in_title:
            self.title_text += data
        if self._in_script and data.strip():
            self.err("inline script")


def check_html():
    path = os.path.join(ROOT, "index.html")
    p = HtmlChecker(path)
    p.feed(read(path))
    p.close()
    for tag, line in p.stack:
        finding(path, line, "<%s> is never closed" % tag)
    for flag, what in ((p.doctype, "<!doctype html>"), (p.lang, "<html lang>"),
                       (p.charset, '<meta charset="utf-8">'),
                       (p.viewport, '<meta name="viewport">')):
        if not flag:
            finding(path, 1, "missing %s" % what)
    if not (p.title_text or "").strip():
        finding(path, 1, "missing or empty <title>")
    for target, line in p.label_fors:
        if target not in p.ids:
            finding(path, line, "<label for=%r> points at no id" % target)
    for ref, line in p.local_refs:
        if not os.path.exists(os.path.join(ROOT, ref.split("?")[0].split("#")[0])):
            finding(path, line, "missing local file %s" % ref)
    loaded = set(p.scripts)
    for name in sorted(os.listdir(os.path.join(ROOT, "js"))):
        if name.endswith(".js") and "js/" + name not in loaded:
            finding(path, 1, "js/%s is not loaded" % name)


# ---- js ---------------------------------------------------------------------

FORBIDDEN_JS = [
    (r"\.innerHTML\b", "innerHTML"),
    (r"\.outerHTML\b", "outerHTML"),
    (r"\binsertAdjacentHTML\b", "insertAdjacentHTML"),
    (r"\bdocument\.write(ln)?\b", "document.write"),
    (r"\bcreateContextualFragment\b", "createContextualFragment"),
    (r"\bDOMParser\b", "DOMParser"),
    (r"\beval\s*\(", "eval"),
    (r"\bnew\s+Function\b", "new Function"),
    (r"\bset(Timeout|Interval)\s*\(\s*['\"`]", "string passed to setTimeout/setInterval"),
    (r"\bvar\s", "var (use const or let)"),
    (r"\bconsole\.", "console"),
    (r"\bdebugger\b", "debugger"),
]

# Native Element.append and its siblings insert "null" for a null child and
# stringify arrays; outside js/dom.js the views use Maity.dom.append.
NATIVE_INSERT = r"\.(append|prepend|replaceChildren|before|after)\("

# After these characters (or at the start) a "/" begins a regular expression.
REGEX_PREV = set("(,=:[!&|?{};+-*%<>~^")


def strip_js(src, literals=None):
    """Blank out strings, template literals, comments and regex literals,
    keeping newlines, so that patterns and brackets are checked on code only.
    Returns (code, error) where error is (line, message) or None. With
    `literals`, a list, each string and template literal is appended to it
    as (line, text)."""
    out = []
    i, n, line = 0, len(src), 1
    prev = ""  # last significant code character
    while i < n:
        c = src[i]
        if c == "\n":
            line += 1
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
            continue
        if src.startswith("/*", i):
            j = src.find("*/", i + 2)
            if j < 0:
                return None, (line, "unterminated comment")
            chunk = src[i:j + 2]
            line += chunk.count("\n")
            out.append(re.sub(r"[^\n]", " ", chunk))
            i = j + 2
            continue
        if c in "'\"`":
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                elif src[j] == "\n" and c != "`":
                    return None, (line, "unterminated string")
                j += 1
            if j >= n:
                return None, (line, "unterminated string")
            chunk = src[i:j + 1]
            if literals is not None:
                literals.append((line, chunk[1:-1]))
            line += chunk.count("\n") - (1 if c == "\n" else 0)
            out.append(c + re.sub(r"[^\n]", " ", chunk[1:-1]) + c)
            prev = c
            i = j + 1
            continue
        if c == "/" and (prev == "" or prev in REGEX_PREV or re.search(r"\b(return|typeof|case)\s*$", "".join(out[-12:]))):
            j, in_class = i + 1, False
            while j < n:
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == "\n":
                    return None, (line, "unterminated regular expression")
                if src[j] == "[":
                    in_class = True
                elif src[j] == "]":
                    in_class = False
                elif src[j] == "/" and not in_class:
                    break
                j += 1
            out.append("/" + " " * (j - i - 1) + "/")
            prev = "/"
            i = j + 1
            continue
        out.append(c)
        if not c.isspace():
            prev = c
        i += 1
    return "".join(out), None


def check_brackets(path, code):
    pairs = {")": "(", "]": "[", "}": "{"}
    stack = []
    line = 1
    for c in code:
        if c == "\n":
            line += 1
        elif c in "([{":
            stack.append((c, line))
        elif c in pairs:
            if not stack or stack[-1][0] != pairs[c]:
                finding(path, line, "unbalanced %r" % c)
                return
            stack.pop()
    for c, l in stack:
        finding(path, l, "unclosed %r" % c)


def check_js(node):
    files = [os.path.join(ROOT, "js", f) for f in sorted(os.listdir(os.path.join(ROOT, "js")))
             if f.endswith(".js")]
    for path in files:
        src = read(path)
        code, error = strip_js(src)
        if error:
            finding(path, error[0], error[1])
            continue
        start = len(code) - len(code.lstrip())
        if not src.startswith('"use strict";', start):
            finding(path, 1, 'first statement is not "use strict";')
        for lineno, text in enumerate(code.split("\n"), 1):
            for pattern, what in FORBIDDEN_JS:
                if re.search(pattern, text):
                    finding(path, lineno, "forbidden: %s" % what)
            if not path.endswith("dom.js") and re.search(NATIVE_INSERT, text):
                finding(path, lineno, "native append/prepend: use Maity.dom.append")
        # The address is a path (docs/api.md §16.11): js/route.js alone knows how
        # the address bar holds it; nowhere else a fragment route, the hash or
        # the History API, in code, strings or comments (context/routing.md).
        if not path.endswith(os.sep + "route.js"):
            for lineno, text in enumerate(src.split("\n"), 1):
                if "#/" in text:
                    finding(path, lineno, "a fragment route (#/): routes are paths, js/route.js")
                if re.search(r"location\.hash|history\.(pushState|replaceState)", text):
                    finding(path, lineno, "the address outside js/route.js: use Maity.route")
        check_brackets(path, code)
    if node:
        for path in files + [BUNDLE]:
            r = subprocess.run([node, "--check", path], capture_output=True, text=True)
            if r.returncode != 0:
                msg = (r.stderr.strip().splitlines() or ["syntax error"])
                finding(path, 1, "node --check: " + " | ".join(msg[:4]))


# ---- i18n -------------------------------------------------------------------

I18N = os.path.join(ROOT, "i18n")
# The bundles go under js/, the one script directory the hub serves at
# /assets/ (hub/src/maity_hub/shell.py ASSET_DIRS); the JSON stays the source.
I18N_BUNDLES = os.path.join(ROOT, "js", "i18n")
I18N_HEADER = (
    "// Generated by tools/check.py --write from i18n/%s.json. Do not edit.\n"
    "// The page loads this file because file:// cannot fetch() the JSON.\n"
)
I18N_KEY = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$")
PLURAL_FORMS = {"zero", "one", "two", "few", "many", "other"}
PLACEHOLDER = re.compile(r"\{([a-z][a-z0-9_]*)\}")
STRINGS_BASELINE = os.path.join(ROOT, "tools", "strings-baseline.json")
# The fixture hub speaks for the hub, the catalog code is the catalog.
STRINGS_EXEMPT = {"api.js", "i18n.js"}


def placeholders(entry):
    texts = [entry] if isinstance(entry, str) else list(entry.values())
    return set(name for t in texts for name in PLACEHOLDER.findall(t))


def load_catalog(path):
    try:
        data = json.loads(read(path))
    except json.JSONDecodeError as e:
        finding(path, e.lineno, "invalid JSON: %s" % e.msg)
        return None
    if not isinstance(data, dict):
        finding(path, 1, "a catalog is one object of keys")
        return None
    for key, entry in data.items():
        if not I18N_KEY.match(key):
            finding(path, 1, "key %r: dotted lowercase names, as chat.instance.label" % key)
        ok = isinstance(entry, str) or (
            isinstance(entry, dict) and "other" in entry and set(entry) <= PLURAL_FORMS
            and all(isinstance(v, str) for v in entry.values()))
        if not ok:
            finding(path, 1, "key %r: a text, or plural forms with `other`" % key)
    return data


# Literals that read as words but are code: the strict-mode directive.
NOT_PROSE = {"use strict"}


def prose(text):
    """A string literal that reads as words a person sees."""
    if text in NOT_PROSE:
        return False
    if not re.search(r"[A-Za-z]", text) or "${" in text and not re.search(r"[A-Za-z]{2,}\s+[A-Za-z]{2,}", text):
        return False
    tokens = text.split()
    # Class lists, ids, keys and paths: lowercase tokens with - . / or #.
    if all(re.fullmatch(r"[a-z0-9_.#/:-]+", t) for t in tokens) and any(re.search(r"[-./#:]", t) for t in tokens):
        return False
    if re.search(r"[A-Za-z]{2,}\s+[A-Za-z]{2,}", text):
        return True
    return bool(re.fullmatch(r"\s*[A-Z][a-z]+[.!?:…]?\s*", text))


def check_i18n(write):
    catalogs = {}
    names = sorted(f for f in os.listdir(I18N) if f.endswith(".json")) if os.path.isdir(I18N) else []
    for name in names:
        lang = name[:-5]
        path = os.path.join(I18N, name)
        data = load_catalog(path)
        if data is None:
            continue
        catalogs[lang] = data
        body = json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True)
        bundle = (I18N_HEADER % lang + '"use strict";\n\nwindow.MAITY_I18N = window.MAITY_I18N || {};\n'
                  + "window.MAITY_I18N[%s] = %s;\n" % (json.dumps(lang), body))
        js = os.path.join(I18N_BUNDLES, lang + ".js")
        if write:
            os.makedirs(I18N_BUNDLES, exist_ok=True)
            with open(js, "w", encoding="utf-8") as f:
                f.write(bundle)
        elif not os.path.exists(js) or read(js) != bundle:
            finding(js, 1, "stale bundle: run `make fixtures`")
    english = catalogs.get("en")
    if english is None:
        finding(os.path.join(I18N, "en.json"), 1, "missing: English is the catalog every language follows")
        return
    for lang, data in catalogs.items():
        for key, entry in data.items():
            if lang != "en" and key in english and not placeholders(entry) <= placeholders(english[key]):
                finding(os.path.join(I18N, lang + ".json"), 1, "key %r: a placeholder English does not have" % key)
    used = set()
    counts = {}
    for f in sorted(os.listdir(os.path.join(ROOT, "js"))):
        if not f.endswith(".js"):
            continue
        path = os.path.join(ROOT, "js", f)
        src = read(path)
        literals = []
        code, error = strip_js(src, literals)
        if error:
            continue
        # M.t or Maity.t, found in the code without comments (strip_js keeps
        # every position), its key read from the source at that place.
        for m in re.finditer(r"\b(?:M|Maity)\.t\(\s*", code):
            lineno = code.count("\n", 0, m.start()) + 1
            quote = src[m.end()] if m.end() < len(src) else ""
            close = src.find(quote, m.end() + 1) if quote in ("\"", "'") else -1
            if close < 0:
                finding(path, lineno, "M.t takes its key as a string literal")
                continue
            key = src[m.end() + 1:close]
            used.add(key)
            if key not in english:
                finding(path, lineno, "M.t key %r is not in i18n/en.json" % key)
        if f not in STRINGS_EXEMPT:
            counts[f] = sum(1 for _, text in literals if prose(text))
    for key in sorted(set(english) - used):
        finding(os.path.join(I18N, "en.json"), 1, "key %r is used nowhere" % key)
    # Without a baseline file, --write takes today's counts once; after that a
    # file it does not name, a new one, is allowed none.
    first = not os.path.exists(STRINGS_BASELINE)
    baseline = counts if first and write else ({} if first else json.loads(read(STRINGS_BASELINE)))
    for f, n in sorted(counts.items()):
        allowed = baseline.get(f, 0)
        if n > allowed:
            finding(os.path.join(ROOT, "js", f), 1,
                    "%d prose string literal(s), %d allowed: new text goes into i18n/en.json, read with M.t"
                    % (n, allowed))
    if write:
        lowered = {f: min(n, baseline.get(f, 0)) for f, n in sorted(counts.items()) if min(n, baseline.get(f, 0))}
        with open(STRINGS_BASELINE, "w", encoding="utf-8") as fh:
            fh.write(json.dumps(lowered, indent=2, sort_keys=True) + "\n")


# ---- the landing page's script ----------------------------------------------

# It ships with the hub (its own route, §16.7), so the page has it without
# the dashboard's files; it is checked here with the dashboard's rules.
LANDING_JS = os.path.join(os.path.dirname(ROOT), "hub", "src", "maity_hub", "landing_assets", "landing.js")
LANDING_JS_MAX = 10 * 1024
# §16.7: it reads the page's own DOM and makes no request of any kind.
LANDING_FORBIDDEN = [
    (r"\bfetch\s*\(", "fetch"),
    (r"\bXMLHttpRequest\b", "XMLHttpRequest"),
    (r"\bWebSocket\b", "WebSocket"),
    (r"\bEventSource\b", "EventSource"),
    (r"\bsendBeacon\b", "sendBeacon"),
    (r"\bimport\s*\(", "import()"),
    (r"\.src\s*=", "setting a src"),
    (r"\.href\s*=", "setting an href"),
]


def check_landing_js(node):
    """The public landing page's one script (docs/api.md §16.7): at most
    10 KiB, the rules of js/*.js, and no request."""
    if not os.path.exists(LANDING_JS):
        finding(LANDING_JS, 1, "missing: the landing page loads it (§16.7)")
        return
    src = read(LANDING_JS)
    if len(src.encode("utf-8")) > LANDING_JS_MAX:
        finding(LANDING_JS, 1, "%d bytes, at most %d (§16.7)" % (len(src.encode("utf-8")), LANDING_JS_MAX))
    code, error = strip_js(src)
    if error:
        finding(LANDING_JS, error[0], error[1])
        return
    start = len(code) - len(code.lstrip())
    if not src.startswith('"use strict";', start):
        finding(LANDING_JS, 1, 'first statement is not "use strict";')
    for lineno, text in enumerate(code.split("\n"), 1):
        for pattern, what in FORBIDDEN_JS + LANDING_FORBIDDEN:
            if re.search(pattern, text):
                finding(LANDING_JS, lineno, "forbidden: %s" % what)
    check_brackets(LANDING_JS, code)
    if node:
        r = subprocess.run([node, "--check", LANDING_JS], capture_output=True, text=True)
        if r.returncode != 0:
            msg = (r.stderr.strip().splitlines() or ["syntax error"])
            finding(LANDING_JS, 1, "node --check: " + " | ".join(msg[:4]))


# ---- css --------------------------------------------------------------------

def check_css():
    path = os.path.join(ROOT, "css", "app.css")
    src = read(path)
    code = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), src, flags=re.S)
    check_brackets(path, code)
    defined = set(re.findall(r"(--[\w-]+)\s*:", code))
    for lineno, text in enumerate(code.split("\n"), 1):
        for name in re.findall(r"var\((--[\w-]+)", text):
            if name not in defined:
                finding(path, lineno, "undefined custom property %s" % name)


# ---- whitespace -------------------------------------------------------------

def check_whitespace():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and d != "__pycache__"]
        for name in filenames:
            if not name.endswith((".html", ".js", ".css", ".json", ".md", ".py")) and name != "Makefile":
                continue
            path = os.path.join(dirpath, name)
            src = read(path)
            if src and not src.endswith("\n"):
                finding(path, src.count("\n") + 1, "no final newline")
            for lineno, text in enumerate(src.split("\n"), 1):
                if text != text.rstrip():
                    finding(path, lineno, "trailing whitespace")
                if "\t" in text and name != "Makefile":
                    finding(path, lineno, "tab")


