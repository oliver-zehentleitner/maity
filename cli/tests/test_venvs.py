"""venvs.py: the dev venvs a runner builds for a Claude Code coder's clone (`clone_venvs`;
cli/context/runner.md). Nothing from the clone runs outside the sandbox: the lock comes from a
fetch of the runner's own, only pinned and hashed requirements pass, pip installs wheels only,
the clone's own package is named by a `.pth`, and a link the agent put on the way is never
followed."""

from __future__ import annotations

