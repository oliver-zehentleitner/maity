from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest
from test_adapters import context
from test_supervisor import REPO, placement, world  # noqa: F401 - world is a fixture

from maity.runner import adapters, config, skills, venvs
from maity.runner.asuser import AsUser

H = "a" * 64
UV_LOCK = f"""# This file was autogenerated by uv via the following command:
#    uv pip compile --universal --generate-hashes requirements/dev.in
anyio==4.15.1 \\
    --hash=sha256:{H} \\
    --hash=sha256:{"b" * 64}
    # via starlette
colorama==0.4.6 ; sys_platform == 'win32' \\
    --hash=sha256:{H}
uvicorn[standard]==0.54.0 \\
    --hash=sha256:{H}
"""


def test_a_uv_lock_with_markers_extras_and_comments_passes_one_line_per_requirement() -> None:
    assert venvs.check_lock(UV_LOCK).splitlines() == [
        f"anyio==4.15.1 --hash=sha256:{H} --hash=sha256:{'b' * 64}",
        f"colorama==0.4.6 ; sys_platform == 'win32' --hash=sha256:{H}",
        f"uvicorn[standard]==0.54.0 --hash=sha256:{H}",
    ]


@pytest.mark.parametrize(
    "line",
    [
        "-e .",
        f"--index-url https://evil.example/simple --hash=sha256:{H}",
        f"evil @ https://evil.example/evil.whl --hash=sha256:{H}",
        f"anyio>=4 --hash=sha256:{H}",
        "anyio==4.15.1",  # no hash
        "-r other.txt",
        f"./local.whl --hash=sha256:{H}",
        f"anyio==4.15.1 --hash=md5:{'a' * 32}",
        f"anyio==4.15.1 --hash=sha256:{H} --no-binary=:all:",
        # After an environment marker too, whose characters alone would let an option through.
        f"anyio==4.15.1 ; python_version>'3' --pre --hash=sha256:{H}",
        f"anyio==4.15.1 ; python_version>'3' --find-links=. --hash=sha256:{H}",
        f"anyio==4.15.1 ; python_version>'3' --config-settings=x=y --hash=sha256:{H}",
        f"anyio==4.15.1 ; python_version>'3' --global-option=x --hash=sha256:{H}",
        f"anyio==4.15.1 ; python_version>'3' -e . --hash=sha256:{H}",
    ],
)
def test_anything_but_a_pinned_hashed_requirement_refuses_the_lock(line: str) -> None:
    with pytest.raises(venvs.Unavailable, match="no pinned, hashed requirement"):
        venvs.check_lock(f"anyio==4.15.1 --hash=sha256:{H}\n{line}\n")


def test_an_empty_or_oversized_lock_is_refused() -> None:
    with pytest.raises(venvs.Unavailable, match="names no requirement"):
        venvs.check_lock("# nothing\n")
    with pytest.raises(venvs.Unavailable, match="larger than"):
        venvs.check_lock("x" * (venvs.MAX_LOCK_BYTES + 1))


def test_the_lock_is_the_fetched_commits_never_the_work_trees(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The runner fetches the placement's branch into a bare repository of its own and reads the
    lock there; a lock the agent wrote in its work tree is never read."""
    calls: list[tuple[Any, ...]] = []

    def fake_git(git_dir: Path, *args: str, binary: bool = False) -> str:
        calls.append((git_dir, *args))
        return UV_LOCK if args[0] == "show" else ""

    monkeypatch.setattr(skills, "_git", fake_git)
    clone = tmp_path / "clone"
    (clone / "hub" / "requirements").mkdir(parents=True)
    (clone / "hub" / "requirements" / "dev.txt").write_text("-e .\n")  # the agent's own
    repository = "https://github.com/acme/maity"
    git_dir = venvs.fetch(tmp_path / "venvs", "plc-0003", repository, "agent-b/x")
    assert git_dir == tmp_path / "venvs" / "plc-0003" / ".git-locks"
    assert venvs.lock_of(git_dir, "hub") == venvs.check_lock(UV_LOCK)
    fetched = [c for c in calls if c[1] == "fetch"]
    assert fetched == [(git_dir, "fetch", "--quiet", "--depth", "1", "--no-tags", "--",
                        "https://github.com/acme/maity", "agent-b/x")]  # fmt: skip
    assert (git_dir, "show", "FETCH_HEAD:hub/requirements/dev.txt") in calls


def _fake_run(record: list[list[str]]) -> Any:
    """venvs._run as far as the tests need it: `-m venv` makes the venv's layout, pip records."""

    def run(argv: list[str], timeout: int) -> None:
        record.append(argv)
        if argv[1:3] == ["-m", "venv"]:
            fresh = Path(argv[3])
            (fresh / "bin").mkdir(parents=True)
            (fresh / "bin" / "python").touch()
            (fresh / "lib" / "python3.13" / "site-packages").mkdir(parents=True)

    return run


def test_pip_installs_hashed_wheels_only_and_never_the_clone(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    record: list[list[str]] = []
    monkeypatch.setattr(venvs, "_run", _fake_run(record))
    clone = tmp_path / "clone"
    lock = venvs.check_lock(UV_LOCK)
    venv = venvs.build(tmp_path / "venvs", "plc-0003", "hub", lock, clone)
    assert venv == tmp_path / "venvs" / "plc-0003" / "hub"
    [make, pip] = record
    # The system Python makes the venv, never one under the test's (or a clone's) tree.
    assert make[1:3] == ["-m", "venv"] and not make[0].startswith(str(tmp_path))
    assert {"--require-hashes", "--only-binary=:all:", "--no-deps"} <= set(pip)
    assert "-e" not in pip and not [a for a in pip if a.startswith(str(clone))]
    assert (venv / "requirements.txt").read_text() == lock
    pth = venv / "lib" / "python3.13" / "site-packages" / "_maity_clone_hub.pth"
    assert pth.read_text() == f"{clone / 'hub' / 'src'}\n"
    assert not [p for p in venv.parent.iterdir() if p.name.startswith(".hub.")]  # no leftover


def test_the_same_lock_for_the_same_clone_is_not_built_again_and_a_new_one_replaces_it(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    record: list[list[str]] = []
    monkeypatch.setattr(venvs, "_run", _fake_run(record))
    clone, lock = tmp_path / "clone", venvs.check_lock(UV_LOCK)
    first = venvs.build(tmp_path / "venvs", "plc-0003", "hub", lock, clone)
    venvs.build(tmp_path / "venvs", "plc-0003", "hub", lock, clone)
    assert len(record) == 2  # one venv, one pip: the second call reused it
    newer = venvs.check_lock(f"anyio==4.16.0 --hash=sha256:{H}\n")
    again = venvs.build(tmp_path / "venvs", "plc-0003", "hub", newer, clone)
    assert again == first and len(record) == 4
    assert (again / "requirements.txt").read_text() == newer
    assert [p.name for p in again.parent.iterdir()] == ["hub"]  # the old one gone, no leftovers


def test_a_failed_build_leaves_no_half_venv_and_keeps_the_built_one(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    record: list[list[str]] = []
    monkeypatch.setattr(venvs, "_run", _fake_run(record))
    clone = tmp_path / "clone"
    built = venvs.build(tmp_path / "venvs", "plc-0003", "hub", venvs.check_lock(UV_LOCK), clone)

    def failing(argv: list[str], timeout: int) -> None:
        _fake_run([])(argv, timeout)
        if "pip" in argv:
            raise venvs.Unavailable("pip exited 1: no wheel")

    monkeypatch.setattr(venvs, "_run", failing)
    other = venvs.check_lock(f"x==1 --hash=sha256:{H}\n")
    with pytest.raises(venvs.Unavailable, match="no wheel"):
        venvs.build(tmp_path / "venvs", "plc-0003", "hub", other, clone)
    assert [p.name for p in built.parent.iterdir()] == ["hub"]
    assert (built / "requirements.txt").read_text() == venvs.check_lock(UV_LOCK)


def test_a_swap_that_fails_puts_the_old_venv_back(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The old venv is set aside, not removed, until the new one stands in its place."""
    monkeypatch.setattr(venvs, "_run", _fake_run([]))
    clone = tmp_path / "clone"
    built = venvs.build(tmp_path / "venvs", "plc-0003", "hub", venvs.check_lock(UV_LOCK), clone)
    rename = Path.rename

    def failing(self: Path, target: Any) -> Path:
        if self.name.startswith(".hub.new-"):
            raise OSError("rename refused")
        return rename(self, target)

    monkeypatch.setattr(Path, "rename", failing)
    other = venvs.check_lock(f"x==1 --hash=sha256:{H}\n")
    with pytest.raises(OSError, match="rename refused"):
        venvs.build(tmp_path / "venvs", "plc-0003", "hub", other, clone)
    assert [p.name for p in built.parent.iterdir()] == ["hub"]
    assert (built / "requirements.txt").read_text() == venvs.check_lock(UV_LOCK)


def test_the_link_is_made_only_where_nothing_stands_below_a_real_directory(tmp_path: Path) -> None:
    venv = tmp_path / "venvs" / "plc-0003" / "hub"
    venv.mkdir(parents=True)
    clone = tmp_path / "clone"
    (clone / "hub").mkdir(parents=True)
    assert venvs.link(clone, "hub", venv)
    assert os.readlink(clone / "hub" / ".venv") == str(venv)
    assert venvs.link(clone, "hub", venv)  # the same link stays
    (clone / "cli" / ".venv").mkdir(parents=True)  # a venv of the agent's own
    assert not venvs.link(clone, "cli", venv)
    assert (clone / "cli" / ".venv").is_dir() and not (clone / "cli" / ".venv").is_symlink()


def test_a_link_the_agent_put_on_the_way_is_never_followed(tmp_path: Path) -> None:
    venv = tmp_path / "venvs" / "plc-0003" / "hub"
    venv.mkdir(parents=True)
    elsewhere = tmp_path / "home"
    elsewhere.mkdir()
    clone = tmp_path / "clone"
    clone.mkdir()
    (clone / "hub").symlink_to(elsewhere)
    assert not venvs.link(clone, "hub", venv)
    assert list(elsewhere.iterdir()) == []


def test_a_closed_placements_venvs_are_removed(tmp_path: Path) -> None:
    (tmp_path / "venvs" / "plc-0003" / "hub" / "bin").mkdir(parents=True)
    (tmp_path / "venvs" / "plc-0004" / "hub").mkdir(parents=True)
    venvs.remove(tmp_path / "venvs", "plc-0003")
    assert [p.name for p in (tmp_path / "venvs").iterdir()] == ["plc-0004"]


def test_the_session_reads_and_runs_its_venvs_and_never_writes_them(tmp_path: Path) -> None:
    venv = tmp_path / "venvs" / "plc-0003" / "hub"
    settings = adapters.claude_settings(context(tmp_path, sandbox=True, venvs=(venv,)))
    allow, deny = settings["permissions"]["allow"], settings["permissions"]["deny"]
    assert f"Read(/{venv}/**)" in allow
    assert not [r for r in allow if str(venv) in r and not r.startswith("Read(")]
    assert f"Edit(/{venv}/**)" in deny
    fs = settings["sandbox"]["filesystem"]
    assert str(venv) in fs["denyWrite"]
    assert not [p for p in fs.get("allowWrite", []) if str(venv).startswith(p)]
    assert not [p for p in fs["denyRead"] if str(venv).startswith(p)]


# --- the supervisor's start step ------------------------------------------------------------

CLAUDE = config.Harness("claude-code", ("interactive",), "interactive")


@pytest.fixture
def sup(world: Any, tmp_path: Path) -> Any:  # noqa: F811 - the imported fixture
    """A supervisor whose configuration names hub and cli for dev venvs."""
    s, _backend, _reports, _clock, logs = world
    assert s.cfg.local is not None
    local = replace(s.cfg.local, clone_venvs=("hub", "cli"))
    s.cfg = replace(s.cfg, local=local, venvs_dir=tmp_path / "venvs")
    s.test_logs = logs
    return s


def _fakes(monkeypatch: pytest.MonkeyPatch, fail: str | None = None) -> list[tuple[Any, ...]]:
    calls: list[tuple[Any, ...]] = []

    def fetch(venvs_dir: Path, placement_id: str, repository: str, branch: str | None) -> Path:
        calls.append(("fetch", placement_id, repository, branch))
        return venvs_dir / placement_id / ".git-locks"

    def lock_of(git_dir: Path, sub: str) -> str:
        if sub == fail:
            raise venvs.Unavailable("the lock holds a line that is no pinned, hashed requirement")
        return f"{sub}==1 --hash=sha256:{H}\n"

    def build(venvs_dir: Path, placement_id: str, sub: str, lock: str, clone: Path) -> Path:
        calls.append(("build", sub, lock, clone))
        made = venvs_dir / placement_id / sub
        made.mkdir(parents=True, exist_ok=True)
        return made

    monkeypatch.setattr(venvs, "fetch", fetch)
    monkeypatch.setattr(venvs, "lock_of", lock_of)
    monkeypatch.setattr(venvs, "build", build)
    return calls


def _clone(tmp_path: Path) -> SimpleNamespace:
    repo = tmp_path / "ws" / "maity" / "agent-3"
    for sub in ("hub", "cli"):
        (repo / sub).mkdir(parents=True)
    return SimpleNamespace(repo=repo)


def test_a_claude_code_start_builds_and_links_each_named_venv(
    sup: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls = _fakes(monkeypatch)
    place = _clone(tmp_path)
    work = {"clone": "agent-3", "branch": "agent-b/x", "repository": REPO}
    p = placement(harness="claude-code", workspace=work)
    built = sup._venvs(p, CLAUDE, place, sup.targets[sup._default_target()])
    home = (tmp_path / "venvs" / "plc-0003").resolve()
    assert built == (home / "hub", home / "cli")
    assert calls[0] == ("fetch", "plc-0003", REPO, "agent-b/x")
    assert [c[1] for c in calls if c[0] == "build"] == ["hub", "cli"]
    assert os.readlink(place.repo / "hub" / ".venv") == str(built[0])


def test_a_venv_that_cannot_be_had_is_logged_and_the_others_are_built(
    sup: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls = _fakes(monkeypatch, fail="hub")
    target = sup.targets[sup._default_target()]
    built = sup._venvs(placement(harness="claude-code"), CLAUDE, _clone(tmp_path), target)
    assert [b.name for b in built] == ["cli"]
    assert [c[1] for c in calls if c[0] == "build"] == ["cli"]
    assert any("no dev venv for hub: the lock holds a line" in line for line in sup.test_logs)


def test_no_venvs_for_another_harness_or_without_the_setting(
    sup: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls = _fakes(monkeypatch)
    target = sup.targets[sup._default_target()]
    codex = config.Harness("codex", ("interactive",), "interactive")
    assert sup._venvs(placement(), codex, _clone(tmp_path), target) == ()
    assert sup.cfg.local is not None
    sup.cfg = replace(sup.cfg, local=replace(sup.cfg.local, clone_venvs=()))
    again = sup._venvs(placement(harness="claude-code"), CLAUDE, _clone(tmp_path / "b"), target)
    assert again == ()
    assert calls == []


def test_where_the_agents_are_another_user_nothing_is_built_and_it_is_said(
    sup: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls = _fakes(monkeypatch)
    target = sup.targets[sup._default_target()]
    other = replace(target, as_user=AsUser("agents"))
    assert sup._venvs(placement(harness="claude-code"), CLAUDE, _clone(tmp_path), other) == ()
    assert calls == []
    assert any("no dev venvs: the runner builds them only where" in line for line in sup.test_logs)
